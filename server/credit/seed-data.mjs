// 15 seed memories. They are deliberately asymmetric so the two limits are
// visibly different: Bob has a strong repayment record, Alice has one default.
// Timestamps are relative to the seed run, which keeps the 7-day recency bonus
// meaningful whenever the demo is recorded.

function daysAgo(days, hour = 10, minute = 15) {
  const date = new Date(Date.now() - days * 24 * 60 * 60 * 1000)
  date.setHours(hour, minute, 0, 0)
  return date.toISOString().replace(/\.\d{3}Z$/, 'Z')
}

